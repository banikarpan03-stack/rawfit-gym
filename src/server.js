function sql(sqlStr) {
  if (!isPostgres) return sqlStr;
  let i = 0;
  return sqlStr.replace(/\?/g, () => `$${++i}`);
}

async function dbGet(sqlStr, params = []) {
  const db = getDb();
  if (isPostgres) {
    const { rows } = await db.pool.query(sql(sqlStr), params);
    return rows[0];
  }
  return db.prepare(sqlStr).get(...params);
}

async function dbAll(sqlStr, params = []) {
  const db = getDb();
  if (isPostgres) {
    const { rows } = await db.pool.query(sql(sqlStr), params);
    return rows;
  }
  return db.prepare(sqlStr).all(...params);
}

async function dbRun(sqlStr, params = []) {
  const db = getDb();
  if (isPostgres) {
    return db.pool.query(sql(sqlStr), params);
  }
  return db.prepare(sqlStr).run(...params);
}

function generateToken(payload) {
  return jwt.sign(payload, JWT_SECRET, { expiresIn: "7d" });
}

function verifyToken(req, res, next) {
  const auth = req.headers.authorization;
  if (!auth || !auth.startsWith("Bearer ")) return res.status(401).json({ error: "Unauthorized" });
  try {
    req.user = jwt.verify(auth.split(" ")[1], JWT_SECRET);
    next();
  } catch {
    res.status(401).json({ error: "Invalid token" });
  }
}

function calcDistance(lat1, lon1, lat2, lon2) {
  const R = 6371000;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos((lat1 * Math.PI) / 180) * Math.cos((lat2 * Math.PI) / 180) * Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function generateUniqueCode() {
  const year = new Date().getFullYear();
  const rand = Math.floor(Math.random() * 10000).toString().padStart(4, "0");
  return `RM-${year}-${rand}`;
}

